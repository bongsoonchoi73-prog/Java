public class OverriDing {
     /*
      * Overriding
      * 
      * - 자식클래스에서 상속받고 있는 부모클래스의 메소드를 재정의하는 것
      * - 자식클래스에 존재하는 메소드테이블에 새로운 내용으로 덮어씀
      * 
      * 오버라이딩의 성립조건
      * 
      * 1. 부모클래스의 메소드와 메소드명 동일
      * 2. 매개변수가 완전히 동일해야함(자료형, 개수, 순서)
      * 3. 반환형도 동일해야함
      * 4. 부모메소드의 접근제한자보다 공유범위가 같거나 넓어야함
      * 
      * -- 개발자들끼리의 암묵적인 약속 : 오버라이딩한 메소드는 반드시 @Override를 붙여주자
      * @Annotation (엔오테이션)
      * 
      * 1. 실수를 줄일 수 있다
      * 2. 오버라이딩한 메소드
      * 
      * 에노테이션 없어도 오버라이딩 잘 구현 가능하지만 약속을 지키자
      */
}
